export interface ServiceWorkerBuild {
  /** Cache name including the build identity, so a new build replaces it. */
  readonly cacheName: string;
  /** Base-absolute paths of the versioned shell and brand assets. */
  readonly precache: readonly string[];
  /** Base-absolute path of the application shell document. */
  readonly shell: string;
}

const forbidden = [
  '/api/',
  '/media/',
  '/delivery/',
  '/s/',
  '/health',
  '/metrics',
];

/**
 * Rejects anything that is not a public, versioned shell or brand asset. API
 * responses, image bytes, share pages, and anything else that can carry
 * account data must never enter the cache.
 */
export function isCacheableAsset(path: string): boolean {
  if (!path.startsWith('/') || path.includes('..')) {
    return false;
  }

  const [withoutQuery] = path.split(/[?#]/);
  const lowered = (withoutQuery ?? '').toLowerCase();

  if (forbidden.some((prefix) => lowered.includes(prefix))) {
    return false;
  }

  return (
    lowered.endsWith('.js') ||
    lowered.endsWith('.css') ||
    lowered.endsWith('.svg') ||
    lowered.endsWith('.png') ||
    lowered.endsWith('.ico') ||
    lowered.endsWith('.webmanifest') ||
    lowered.endsWith('/index.html')
  );
}

/**
 * Generates the service worker. It precaches the built shell and brand assets,
 * serves them from the cache, falls back to the cached shell for navigations,
 * and passes every other request straight to the network.
 */
export function buildServiceWorker(build: ServiceWorkerBuild): string {
  const precache = [...new Set(build.precache)].filter(isCacheableAsset).sort();
  if (!precache.includes(build.shell)) {
    precache.push(build.shell);
    precache.sort();
  }

  return `// Generated by src/build/serviceWorker.ts. Do not edit.
const CACHE = ${JSON.stringify(build.cacheName)};
const SHELL = ${JSON.stringify(build.shell)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const CACHED = new Set(PRECACHE);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((name) => name.startsWith('vistara-shell-') && name !== CACHE)
            .map((name) => caches.delete(name)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') {
    return;
  }

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) {
    return;
  }

  if (CACHED.has(url.pathname)) {
    event.respondWith(
      caches
        .open(CACHE)
        .then((cache) => cache.match(url.pathname))
        .then((cached) => cached || fetch(request)),
    );
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() =>
        caches
          .open(CACHE)
          .then((cache) => cache.match(SHELL))
          .then(
            (cached) =>
              cached ||
              new Response('', { status: 504, statusText: 'Offline' }),
          ),
      ),
    );
  }
});
`;
}
